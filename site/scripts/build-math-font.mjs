// Subsets STIX Two Math (SIL OFL) to the mathematical blocks the graph's text uses
// (arrows, operators, letterlike ℝ ℓ, sub- and superscripts …) and writes the font
// plus a matching @font-face. (Libertinus Math was tried first: its packaged arrows
// → ⊣ ⟶ render blank in Chromium.) The body text font has none of these glyphs, so the
// browser falls back to this one per character, and only downloads it when needed.
import { mkdir, readFile, writeFile } from "node:fs/promises";
import subsetFont from "subset-font";

const SRC = new URL("../node_modules/@fontsource/stix-two-math/files/stix-two-math-latin-400-normal.woff2", import.meta.url);
const OUT = new URL("../.generated/fonts/", import.meta.url);

const RANGES = [
  [0x2016, 0x2016], // ‖
  [0x2032, 0x2037], // primes
  [0x2070, 0x209f], // super- and subscripts
  [0x2100, 0x214f], // letterlike (ℝ ℕ ℓ)
  [0x2190, 0x21ff], // arrows
  [0x2200, 0x22ff], // mathematical operators
  [0x2308, 0x230b], // ceilings and floors
  [0x27c0, 0x27ff], // misc. mathematical symbols A (⟨ ⟩), long arrows (⟶ ⟺)
];

const text = RANGES.flatMap(([a, b]) => Array.from({ length: b - a + 1 }, (_, i) => String.fromCodePoint(a + i))).join("");
// No layout closure: running text never needs the stretchy and size variants.
const font = await subsetFont(await readFile(SRC), text, { targetFormat: "woff2", noLayoutClosure: true });
const hex = (n) => n.toString(16).toUpperCase();
const range = RANGES.map(([a, b]) => (a === b ? `U+${hex(a)}` : `U+${hex(a)}-${hex(b)}`)).join(", ");

await mkdir(OUT, { recursive: true });
await writeFile(new URL("arche-math.woff2", OUT), font);
await writeFile(
  new URL("arche-math.css", OUT),
  `/* Generated by scripts/build-math-font.mjs. */
@font-face {
  font-family: "Arche Math";
  src: url("./arche-math.woff2") format("woff2");
  font-display: swap;
  unicode-range: ${range};
}
`,
);
console.log(`wrote .generated/fonts/arche-math.woff2 (${(font.length / 1024).toFixed(1)} KB)`);
